            echo '<p><strong>Server Time:</strong> ' . date('Y-m-d H:i:s') . '</p>';
            echo '</div>';
            
            // Generate dynamic welcome message (BACKEND processing)
            echo '<div class="info-box">';
            echo '<h3>🎉 DYNAMIC WELCOME MESSAGE (Generated by PHP on Server)</h3>';
            echo '<p>Hello <strong>' . htmlspecialchars($name) . '</strong>!</p>';
            echo '<p>Great choice learning <strong>' . htmlspecialchars($technology) . '</strong>! ';
            echo 'This technology runs on the ' . ($technology == 'PHP' ? 'SERVER (BACKEND)' : 'BROWSER (FRONTEND)') . '.</p>';
            
            if (!empty($message)) {
                echo '<p><strong>Your message:</strong> "' . htmlspecialchars($message) . '"</p>';
            }
            
            echo '<p>Your form data was processed by <code>simple_processor.php</code> on the server.</p>';
            echo '</div>';
            
